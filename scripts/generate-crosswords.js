// Index common words by constrained positions
function findWords(constraints) {
  // constraints: array of [position, letter] pairs
  let candidates = goodWords;
  for (const [pos, letter] of constraints) {
    candidates = candidates.filter(w => w[pos] === letter);
  }
  return candidates;
}

