function getClue(word) {
  return clueBank[word] || `___ (write clue for ${word})`;
}

// Generate 28 puzzles for February 2026
function generateFebruaryPuzzles() {
  const puzzles = {};
  const allUsedWords = new Set();
  
  for (let day = 1; day <= 28; day++) {
    const dateKey = `2026-02-${String(day).padStart(2, '0')}`;
    
    const result = generatePuzzle(allUsedWords);
    if (!result) {
      console.error(`Failed to generate puzzle for ${dateKey}`);
      continue;
    }
    
    for (const w of result.allWords) allUsedWords.add(w);
    
    puzzles[dateKey] = {
      grid: result.grid,
      across: {
        '1': getClue(result.across.a1),
        '4': getClue(result.across.a4),
        '5': getClue(result.across.a5),
      },
      down: {
        '1': getClue(result.down.d1),
        '2': getClue(result.down.d2),
        '3': getClue(result.down.d3),
      },
      solution: {
        across: {
          '1': result.across.a1,
          '4': result.across.a4,
          '5': result.across.a5,
        },
        down: {
          '1': result.down.d1,
          '2': result.down.d2,
          '3': result.down.d3,
        },
      },
    };
    
    console.log(`✓ ${dateKey}: A=[${result.across.a1},${result.across.a4},${result.across.a5}] D=[${result.down.d1},${result.down.d2},${result.down.d3}]`);
  }
  
  return puzzles;
}

