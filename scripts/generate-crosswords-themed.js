/**
 * Themed Crossword Generator v3 — POOL-BASED HYBRID
 * 
 * Strategy:
 *   - Each theme defines a POOL of ~25-35 themed 5-letter words with clues
 *   - For each puzzle, try ALL ordered triples (A1, A4, A5) from the pool
 *   - Down words are found algorithmically from the full 12k-word dictionary
 *   - All 6 words get rich descriptive clues
 * 
 * Grid: 5×5, blocks at [1][1],[1][3],[3][1],[3][3]
 * D1=A1[0],_,A4[0],_,A5[0]  D2=A1[2],_,A4[2],_,A5[2]  D3=A1[4],_,A4[4],_,A5[4]
 */
const fs = require("fs");
const dictionary = require("../src/data/dictionary/common-english-words.json");

const allWords = dictionary
  .filter(w => w.length === 5 && /^[a-z]+$/.test(w))
  .map(w => w.toUpperCase());

// Index by letters at positions 0,2,4 (intersection points)
const byPattern = {};
for (const w of allWords) {
  const key = `${w[0]}${w[2]}${w[4]}`;
  if (!byPattern[key]) byPattern[key] = [];
  byPattern[key].push(w);
}

/** Get ALL possible down-word combos for a given across triple, return best-scored one */
function findBestDownWords(a1, a4, a5, clueBank) {
  const d1key = `${a1[0]}${a4[0]}${a5[0]}`;
  const d2key = `${a1[2]}${a4[2]}${a5[2]}`;
  const d3key = `${a1[4]}${a4[4]}${a5[4]}`;
  const used = new Set([a1, a4, a5]);
  
  const d1opts = (byPattern[d1key] || []).filter(w => !used.has(w));
  const d2opts = (byPattern[d2key] || []).filter(w => !used.has(w));
  const d3opts = (byPattern[d3key] || []).filter(w => !used.has(w));
  
  if (!d1opts.length || !d2opts.length || !d3opts.length) return null;

  // Score each word: 3 if in clueBank, 0 if not
  const scoreWord = w => clueBank[w] ? 3 : 0;
  
  let best = null;
  let bestScore = -1;
  
  for (const w1 of d1opts) {
    const s1 = scoreWord(w1);
    for (const w2 of d2opts) {
      if (w2 === w1) continue;
      const s12 = s1 + scoreWord(w2);
      for (const w3 of d3opts) {
        if (w3 === w1 || w3 === w2) continue;
        const score = s12 + scoreWord(w3);
        if (score > bestScore) {
          bestScore = score;
          best = { d1: w1, d2: w2, d3: w3, score };
          if (score === 9) return best; // perfect — all 3 have clues
        }
      }
    }
  }
  return best;
}

/** Find the BEST valid triple from a theme pool — tries ALL ordered triples */
function findBestTriple(pool, clueBank, usedWords) {
  const words = Object.keys(pool);
  let best = null;
  let bestScore = -1;
  let tried = 0;
  
  for (let i = 0; i < words.length; i++) {
    if (usedWords.has(words[i])) continue;
    for (let j = 0; j < words.length; j++) {
      if (j === i || usedWords.has(words[j])) continue;
      for (let k = 0; k < words.length; k++) {
        if (k === i || k === j || usedWords.has(words[k])) continue;
        tried++;
        const a1 = words[i], a4 = words[j], a5 = words[k];
        const down = findBestDownWords(a1, a4, a5, clueBank);
        if (down) {
          // Also check down words aren't reused
          if (usedWords.has(down.d1) || usedWords.has(down.d2) || usedWords.has(down.d3)) {
            // penalize but don't disqualify
            const penalizedScore = down.score - 1;
            if (penalizedScore > bestScore) {
              bestScore = penalizedScore;
              best = { a1, a4, a5, d1: down.d1, d2: down.d2, d3: down.d3, score: penalizedScore };
            }
            continue;
          }
          const score = down.score;
          if (score > bestScore) {
            bestScore = score;
            best = { a1, a4, a5, d1: down.d1, d2: down.d2, d3: down.d3, score };
            if (score === 9) {
              return { result: best, tried };
            }
          }
        }
      }
    }
  }
  return { result: best, tried };
}

