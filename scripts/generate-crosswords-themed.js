// ==================================================================
// MAIN: Parse CLI args and generate for the target month
// ==================================================================

// Usage: node scripts/generate-crosswords-themed.js [month]
// month is 1-12 (default: current month). Year is always 2026.
const argMonth = parseInt(process.argv[2], 10);
const YEAR = 2026;
const targetMonth = (argMonth >= 1 && argMonth <= 12) ? argMonth : new Date().getMonth() + 1;
const daysInMonth = new Date(YEAR, targetMonth, 0).getDate();
const monthStr = String(targetMonth).padStart(2, "0");

console.log(`\nGenerating ${daysInMonth} themed crosswords for ${YEAR}-${monthStr}\n`);

if (THEMES.length < daysInMonth) {
  console.error(`ERROR: Need ${daysInMonth} themes but only have ${THEMES.length}. Add more themes.`);
  process.exit(1);
}

// Build combined clue bank for scoring (fillClues + all pools)
const allClues = { ...fillClues };
for (const t of THEMES) {
  for (const [word, clue] of Object.entries(t.pool)) {
    allClues[word] = clue;
  }
}

const output = {};
let okCount = 0;
const failures = [];
const missingClueWords = new Set();
const usedWords = new Set(); // prevent duplicate words across puzzles

for (let i = 0; i < daysInMonth; i++) {
  const day = i + 1;
  const date = `${YEAR}-${monthStr}-${String(day).padStart(2, "0")}`;
  const theme = THEMES[i];
  const pool = theme.pool;
  const poolWords = Object.keys(pool);

  process.stdout.write(`Day ${day} (${date}): ${theme.name}  [${poolWords.length} candidates] ... `);

  const { result, tried } = findBestTriple(pool, allClues, usedWords);

  if (result) {
    const { a1, a4, a5, d1, d2, d3, score } = result;
    console.log(`✓ score=${score}/9 tried=${tried}`);
    console.log(`  A=[${a1}, ${a4}, ${a5}] → D=[${d1}, ${d2}, ${d3}]`);

    const d1clue = allClues[d1] || `Clue for ${d1}`;
    const d2clue = allClues[d2] || `Clue for ${d2}`;
    const d3clue = allClues[d3] || `Clue for ${d3}`;

    if (!allClues[d1]) { console.log(`  ⚠ Missing clue for ${d1}`); missingClueWords.add(d1); }
    if (!allClues[d2]) { console.log(`  ⚠ Missing clue for ${d2}`); missingClueWords.add(d2); }
    if (!allClues[d3]) { console.log(`  ⚠ Missing clue for ${d3}`); missingClueWords.add(d3); }

    // Mark all 6 words as used
    [a1, a4, a5, d1, d2, d3].forEach(w => usedWords.add(w));

    output[date] = {
      theme: theme.name,
      grid: [
        [a1[0], a1[1], a1[2], a1[3], a1[4]],
        [d1[1], "", d2[1], "", d3[1]],
        [a4[0], a4[1], a4[2], a4[3], a4[4]],
        [d1[3], "", d2[3], "", d3[3]],
        [a5[0], a5[1], a5[2], a5[3], a5[4]],
      ],
      across: {
        "1": pool[a1],
        "4": pool[a4],
        "5": pool[a5],
      },
      down: {
        "1": d1clue,
        "2": d2clue,
        "3": d3clue,
      },
      solution: {
        across: { "1": a1, "4": a4, "5": a5 },
        down: { "1": d1, "2": d2, "3": d3 },
      },
    };
    okCount++;
  } else {
    console.log(`❌ FAIL — no valid triple from ${poolWords.length} candidates (tried=${tried})`);
    failures.push({ day, theme: theme.name, poolSize: poolWords.length });
  }
}

console.log(`\n${"=".repeat(50)}`);
console.log(`Results: ${okCount}/${daysInMonth} themed puzzles created`);

if (missingClueWords.size > 0) {
  console.log(`\n⚠ Words with missing clues (${missingClueWords.size}):`);
  console.log(`  ${[...missingClueWords].join(", ")}`);
}

if (failures.length > 0) {
  console.log(`\n❌ Failed themes:`);
  failures.forEach(f => console.log(`  Day ${f.day}: ${f.theme} (${f.poolSize} words)`));
}

const outPath = `./src/data/all-data/month-${monthStr}/crossword.json`;
if (okCount === daysInMonth) {
  fs.writeFileSync(outPath, JSON.stringify(output, null, 2) + "\n");
  console.log(`\n✅ All ${daysInMonth} themed puzzles written to month-${monthStr}/crossword.json`);
} else {
  const partialPath = `./src/data/all-data/month-${monthStr}/crossword-partial.json`;
  fs.writeFileSync(partialPath, JSON.stringify(output, null, 2) + "\n");
  console.log(`\n⚠️ ${okCount}/${daysInMonth} written to crossword-partial.json. Fix failing themes.`);
}
