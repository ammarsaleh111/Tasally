/**
 * Get words organized by length
 */
export const getWordsByLength = () => {
  const result = {};
  
  for (const word of Object.keys(WORD_CLUES)) {
    const len = word.length;
    if (!result[len]) {
      result[len] = [];
    }
    result[len].push(word);
  }
  
  return result;
};

/**
 * Get a random clue for a word
 */
export const getClueForWord = (word, usedClues = new Set()) => {
  const upperWord = word.toUpperCase();
  const clues = WORD_CLUES[upperWord];
  
  if (!clues || clues.length === 0) {
    return `Definition of ${word}`;
  }
  
  // Try to find an unused clue
  for (const clue of clues) {
    if (!usedClues.has(clue)) {
      return clue;
    }
  }
  
  // Fall back to first clue
  return clues[0];
};

/**
 * Get all clues for a word
 */
export const getAllCluesForWord = (word) => {
  const upperWord = word.toUpperCase();
  return WORD_CLUES[upperWord] || [`Definition of ${word}`];
};
